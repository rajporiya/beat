export interface PlaylistOwner {
    _id : string,
    fullName? : string,
    imageUrl? : string,
}
export interface PlaylistSummary {
    _id : string,
    name : string,
    description? : string,
    coverImage? : string,
    isPublic : boolean,
    owner? : PlaylistOwner | null,
    songs : Array<{ _id : string, imageUrl? : string }>,
    createdAt? : string,
    updatedAt? : string,
}
export interface PlaylistDetail extends Omit<PlaylistSummary, "songs"> {
    songs : Song[],
}